def test_offsets_set_order_and_positional_order():
    assert utc_text(datetime(2024, 1, 1, tzinfo=UTC)) == "2024-01-01T00:00:00.000000Z"
    a = wire_value(
        dict(
            quality_flags=["z", "a"],
            member_ids=["b", "a"],
            assets=[dict(asset_id="z"), dict(asset_id="a")],
            reasons=["second", "first"],
            reference_years=[2010, 2019],
        )
    )
    assert a["quality_flags"] == ["a", "z"] and a["member_ids"] == ["a", "b"]
    assert a["assets"][0]["asset_id"] == "a"
    assert a["reasons"] == ["second", "first"] and a["reference_years"] == [2010, 2019]


def test_payload_covers_all_inputs_and_retains_upstream_hash_preimage():
    payload = example()
    raw, pin = evidence_content(payload)
    wire = json.loads(raw)
    assert hashlib.sha256(raw).hexdigest() == pin
    assert wire["region"]["name"] == "Synthetic رِیجن"
    assert wire["priority_score"] == "150" and wire["escalation_probability"] is None
    assert wire["model"] is None and wire["baseline_version"] == "power-monthly-v1"
    assert wire["weather"]["series"]["records"] and wire["satellite"]["selected"]
    assert wire["feature"]["missing_flags"] and wire["source_checksums"]
    assert wire["explanation"]["reasons"] == wire["reasons"]
    assert hashlib.sha256(wire["feature_payload_json"].encode()).hexdigest() == wire["feature_hash"]
    assert json.loads(wire["feature_payload_json"])["values"]["frp_max_mw"] == 150


def test_unordered_source_permutations_produce_identical_bytes_without_mutation():
    args = evidence_args()
    before = deepcopy(args)
    first = evidence_content(build_evidence(**args))
    args["firms"]["selected"].reverse()
    args["firms"]["policy"]["batch_ids"].reverse()
    args["pins"].assets.reverse()
    args["pins"].satellite_assets.reverse()
    assert evidence_content(build_evidence(**args)) == first
    assert before["feature"] == args["feature"]


