def test_fixed_decimal_context_ignores_callers_traps_and_exponent_limits():
    from decimal import Inexact

    with localcontext() as context:
        context.prec = 2
        context.Emax = 9
        context.traps[Inexact] = True
        assert decimal_string(1e308) == decimal_string(float("1e308"))
        assert decimal_string(0.1) == "0.10000000000000001"


def test_weighted_and_uncalibrated_model_envelopes_keep_score_semantics():
    from firewatch.ml.inference_bundle import ApprovedScorer
    from firewatch.ml.predict import score_features

    args = evidence_args(missing_weather=True)
    args["score"] = score_features(
        [args["feature"]], "weighted-baseline-v1", scored_at=args["score"].scored_at
    )[0]
    weighted = json.loads(evidence_content(build_evidence(**args))[0])
    assert weighted["scorer_version"] == "weighted-baseline-v1"
    assert weighted["model"] is None and weighted["escalation_probability"] is None
    assert weighted["explanation"]["missing_components"]
    args = evidence_args()
    model_id = uuid4()
    args["approved"] = ApprovedScorer(
        model_id=model_id,
        scorer_version="synthetic-forest-v1",
        artifact_path=Path("synthetic-not-loaded"),
        manifest_sha256="d" * 64,
        approval_status="approved",
        approval_reference="synthetic-test-authority",
    )
    args["score"] = args["score"].model_copy(
        update=dict(
            model_id=model_id,
            scorer_version="synthetic-forest-v1",
            score_kind=ScoreKind.MODEL,
            priority_score=0.9,
            escalation_probability=None,
            explanation=dict(
                method="synthetic-test-only",
                inference_manifest_sha256="d" * 64,
                approval_reference="synthetic-test-authority",
            ),
        )
    )
    wire = json.loads(evidence_content(build_evidence(**args))[0])
    assert wire["model"]["model_id"] == str(model_id)
    assert wire["model"]["inference_manifest_sha256"] == "d" * 64
    assert wire["escalation_probability"] is None and wire["score_kind"] == "model_score"
    assert "artifact_path" not in wire["model"]


def test_public_projection_retains_new_format_without_mutating_hash_preimage():
    from firewatch.api.presentation import evidence_projection
    from firewatch.db.models import Alert

    raw, pin = evidence_content(example())
    alert = Alert(id=uuid4(), canonical_payload=raw, original_hash=pin)
    projection, _ = evidence_projection(alert)
    assert projection["canonicalization_version"] == CANONICALIZATION_VERSION
    assert projection["priority_score"] == "150"
    assert alert.canonical_payload == raw and hashlib.sha256(raw).hexdigest() == pin
