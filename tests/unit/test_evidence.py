@pytest.mark.parametrize(
    "value",
    [
        0.0,
        -0.0,
        0.1,
        1.2345678901234567,
        1e-300,
        5e-324,
        1e308,
        -273.15,
        100.0,
        math.nextafter(1.0, 0),
    ],
)
def test_decimal_precision_roundtrips_binary64(value):
    result = decimal_string(value)
    assert float(result) == value and "e" not in result.lower()
    assert result != "-0" and ("." not in result or not result.endswith("0"))
    with localcontext() as context:
        context.prec = 2
        assert decimal_string(value) == result


@pytest.mark.parametrize("value", [float("nan"), float("inf"), -float("inf")])
def test_nonfinite_rejected_at_every_depth(value):
    with pytest.raises(ValueError):
        wire_value({"outer": [{"invalid": value}]})


def test_golden_wire_vector():
    source = dict(
        schema_version="evidence-v1",
        canonicalization_version=CANONICALIZATION_VERSION,
        priority_score=0.1,
        missing=None,
        count=2,
        flag=True,
        as_of=datetime(2024, 7, 25, 17, tzinfo=timezone(timedelta(hours=5))),
        warnings=["z", "a"],
        reasons=["second", "first"],
        name="آگ",
    )
    expected = (
        '{"as_of":"2024-07-25T12:00:00.000000Z",'
        '"canonicalization_version":"evidence-json-v1","count":2,"flag":true,'
        '"missing":null,"name":"آگ","priority_score":"0.10000000000000001",'
        '"reasons":["second","first"],"schema_version":"evidence-v1",'
        '"warnings":["a","z"]}'
    ).encode()
    assert serialize_evidence(source) == expected
    # Independent fixed SHA pin published with the vector, not generated by the serializer.
    assert (
        hashlib.sha256(expected).hexdigest()
        == "2852aaae3efc3a6720dce0390f85b9a528b6f69868e961da95318b9c7bc55c83"
    )


