def test_unsupported_version_depth_and_size_refused(monkeypatch):
    import firewatch.evidence.serialization as module

    with pytest.raises(ValueError, match="version"):
        serialize_evidence({"schema_version": "evidence-v1"})
    deep = {}
    for _ in range(66):
        deep = {"a": deep}
    with pytest.raises(ValueError, match="nesting"):
        wire_value(deep)
    monkeypatch.setattr(module, "MAX_EVIDENCE_BYTES", 10)
    with pytest.raises(ValueError, match="byte bound"):
        evidence_content(example())


