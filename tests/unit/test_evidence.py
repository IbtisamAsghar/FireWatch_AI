    body = example().model_dump()
    body[field] = (
        []
        if field == "source_checksums"
        else (
            "0" * 64
            if field == "feature_hash"
            else "changed"
            if field in {"feature_payload_json", "baseline_version"}
            else uuid4()
        )
    )
    with pytest.raises(ValueError):
        EvidencePayload.model_validate(body)


